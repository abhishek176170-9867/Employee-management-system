# 1. Gantt Chart
def generate_gantt_chart():
    fig, ax = plt.subplots(figsize=(10, 6), dpi=200)
    phases = [
        ("Deployment", 6, 1, "#4A148C", "Go live, monitoring"),
        ("Testing & QA", 5, 1, "#00695C", "Unit tests, bug fixing"),
        ("Admin & Reporting", 4, 1, "#E65100", "Approvals & CSV export"),
        ("Core Development", 2, 2, "#C2185B", "Leave apply & calculators"),
        ("Database & Schema", 1, 1, "#1565C0", "SQLite tables & seed data"),
        ("Requirements & Design", 0, 1, "#283593", "Scope & UML design"),
    ]

    y_pos = np.arange(len(phases))
    for i, (name, start_wk, dur, color, desc) in enumerate(phases):
        ax.barh(i, dur, left=start_wk, height=0.55, color=color, edgecolor='#333333', linewidth=1.2)
        ax.text(start_wk + dur/2, i, desc, ha='center', va='center', color='white', fontweight='bold', fontsize=9)

    ax.set_yticks(y_pos)
    ax.set_yticklabels([p[0] for p in phases], fontsize=10, fontweight='bold')
    ax.set_xlabel("Project Timeline (Weeks / Milestones)", fontsize=11, fontweight='bold', labelpad=10)
    ax.set_title("Gantt Chart: Employee Leave Management System Project", fontsize=13, fontweight='bold', pad=15)
    ax.set_xlim(0, 8)
    ax.set_xticks(range(9))
    ax.set_xticklabels([f"Week {i}" if i > 0 else "Start" for i in range(9)], fontsize=9)
    ax.grid(axis='x', linestyle='--', alpha=0.5)
    ax.set_facecolor('#F8FAFC')
    fig.patch.set_facecolor('#FFFFFF')
    plt.tight_layout()
    path = os.path.join(OUTPUT_DIR, 'gantt_chart.png')
    plt.savefig(path, bbox_inches='tight')
    plt.close()
    print("Saved:", path)

